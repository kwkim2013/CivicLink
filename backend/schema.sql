-- CivicLink PostgreSQL schema
-- 실행 대상: civiclink 데이터베이스

BEGIN;

CREATE TABLE IF NOT EXISTS app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(500) NOT NULL,
    organization VARCHAR(200),
    department VARCHAR(200),
    display_name VARCHAR(100),
    role VARCHAR(20) NOT NULL DEFAULT 'USER'
);

ALTER TABLE app_users ADD COLUMN IF NOT EXISTS organization VARCHAR(200);
ALTER TABLE app_users ADD COLUMN IF NOT EXISTS department VARCHAR(200);
ALTER TABLE app_users ADD COLUMN IF NOT EXISTS display_name VARCHAR(100);

CREATE TABLE IF NOT EXISTS complaints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES app_users(id),
    title VARCHAR(300) NOT NULL,
    content TEXT NOT NULL,
    category VARCHAR(100),
    status VARCHAR(30) NOT NULL DEFAULT 'RECEIVED'
);

CREATE INDEX IF NOT EXISTS idx_complaints_owner_id ON complaints(owner_id);
CREATE INDEX IF NOT EXISTS idx_complaints_status ON complaints(status);

CREATE TABLE IF NOT EXISTS decisions (
    id BIGINT PRIMARY KEY,
    title VARCHAR(1000),
    category VARCHAR(100),
    payload TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_decisions_category ON decisions(category);

COMMIT;
