package com.civiclink.config;

import org.springframework.beans.factory.annotation.Value;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import javax.sql.DataSource;

@Configuration
public class DatabaseConfig {
    @Bean
    public DataSource dataSource(@Value("${database.url:jdbc:h2:file:${civiclink.data-dir:C:/github/CivicLink/backend/data}/civiclink}") String url,
                                 @Value("${database.username:sa}") String username,
                                 @Value("${database.password:}") String password) {
        DriverManagerDataSource source = new DriverManagerDataSource();
        // Select the JDBC driver that matches the configured database URL.
        // PostgreSQL is used in the deployed application; H2 remains the local fallback.
        source.setDriverClassName(url.startsWith("jdbc:postgresql:")
                ? "org.postgresql.Driver"
                : "org.h2.Driver");
        source.setUrl(url); source.setUsername(username); source.setPassword(password);
        return source;
    }

    @Bean
    public JdbcTemplate jdbcTemplate(DataSource source) {
        JdbcTemplate jdbc = new JdbcTemplate(source);
        jdbc.execute("CREATE TABLE IF NOT EXISTS decisions (id BIGINT PRIMARY KEY, title VARCHAR(1000), category VARCHAR(100), payload TEXT NOT NULL)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS app_users (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username VARCHAR(100) UNIQUE NOT NULL, password_hash VARCHAR(500) NOT NULL, role VARCHAR(20) NOT NULL)");
        jdbc.execute("ALTER TABLE app_users ADD COLUMN IF NOT EXISTS organization VARCHAR(200)");
        jdbc.execute("ALTER TABLE app_users ADD COLUMN IF NOT EXISTS department VARCHAR(200)");
        jdbc.execute("ALTER TABLE app_users ADD COLUMN IF NOT EXISTS display_name VARCHAR(100)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS complaints (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, owner_id BIGINT NOT NULL REFERENCES app_users(id), title VARCHAR(300) NOT NULL, content TEXT NOT NULL, category VARCHAR(100), status VARCHAR(30) NOT NULL)");
        return jdbc;
    }
}

